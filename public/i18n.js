// ---- Забони ҷорӣ ----------------------------------------------------------
let currentLang = (function(){
  try{
    const saved = localStorage.getItem("spt_lang");
    if (saved && LANGUAGES.some(l=>l.code===saved)) return saved;
    // Агар забони браузер англисӣ бошад — англисиро пешниҳод мекунем
    const nav = (navigator.language || "ru").slice(0,2).toLowerCase();
    if (nav === "en") return "en";
    if (nav === "tg") return "tj";
  }catch(e){}
  return "ru";
})();

function getLang(){ return currentLang; }

function setLang(code){
  if (!LANGUAGES.some(l=>l.code===code)) return;
  currentLang = code;
  try{ localStorage.setItem("spt_lang", code); }catch(e){}
  document.documentElement.lang = code === "tj" ? "tg" : code;
}

// Функсияи асосии тарҷума
function t(ru){
  if (currentLang === "ru") return ru;
  const table = DICT[currentLang];
  return (table && table[ru] !== undefined) ? table[ru] : ru;
}

